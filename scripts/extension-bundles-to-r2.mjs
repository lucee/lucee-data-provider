#!/usr/bin/env node
// Makes the OSGi bundles of one Lucee extension resolvable by the update provider
// (update.lucee.org/rest/update/provider/download/<bundle>/<version>).
//
// The provider (apps/updateserver-maven, BundleDownloadService + legacy/MavenMatcher) answers a bundle
// download with a 302 to a jar on a Maven repository, or a 404. It never extracts a jar from a .lex.
// Among the paths it tries on maven.lucee-services.com is
//   org/lucee/<Bundle-SymbolicName>/<Bundle-Version>/<Bundle-SymbolicName>-<Bundle-Version>.jar
// (org.lucee:<Bundle-SymbolicName>:<Bundle-Version>, the layout of the "Upload Maven jar" workflow of
// lucee/Lucee). The Maven bridge worker serves that path from the R2 bucket. So a bundle that only
// ships inside a .lex (for example org.lucee.axis.extension or mssqljdbc4, which were only in the
// legacy S3 bucket extension-downloads) becomes resolvable once its jar is at that key in R2.
//
// What the script does:
//   1. downloads the .lex (Maven coordinates groupId:artifactId:version on MAVEN_REPO, or an https URL)
//   2. reads the bundles it ships (jars/*.jar, Bundle-SymbolicName / Bundle-Version of each manifest)
//      and the bundles its manifest requires (jdbc, cache, orm, webservice, ... entries with a bundle name)
//   3. asks the update provider for each bundle (HEAD, no redirect followed)
//   4. uploads the jar of every bundle the provider cannot resolve to R2, with a minimal pom and
//      .sha1 / .md5 files; maven-metadata.xml is generated by the worker (R2 event notification)
//   5. prints a summary table (also to GITHUB_STEP_SUMMARY)
//
// Never overwrites: every key is checked with HEAD and written with If-None-Match: * (R2 conditional
// write, 412 = already there). Running it again is safe. SNAPSHOT versions are written to the plain
// Maven-layout key (not below R2_SNAPSHOT_PREFIX), so the snapshot lifecycle rule does not remove a
// bundle Lucee installs need; the worker looks up the plain key for SNAPSHOT files too.
//
// Environment:
//   EXTENSION            groupId:artifactId:version or https URL of a .lex (required)
//   DRY_RUN              anything but "false" is a dry run (default), nothing is written
//   MAVEN_REPO           default https://maven.lucee-services.com
//   PROVIDER_URL         default https://update.lucee.org/rest/update/provider/download/
//   R2_ENDPOINT, R2_BUCKET, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY   only needed when DRY_RUN=false
//   R2_PREFIX            optional key prefix (same as the worker's R2_PREFIX)
//
//   EXTENSION=org.lucee:axis-extension:1.4.0.27-SNAPSHOT node scripts/extension-bundles-to-r2.mjs

import { createHash, createHmac } from "node:crypto";
import { inflateRawSync } from "node:zlib";
import { appendFileSync } from "node:fs";

export const USER_AGENT = "lucee-gian-ci-check";
const MAX_LEX_BYTES = 256 * 1024 * 1024;
const SAFE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

// ---------------------------------------------------------------- input

/** URL without query and fragment, a presigned URL is never printed with its signature. */
export function redact(url) {
	try {
		const u = new URL(url);
		return u.origin + u.pathname + (u.search ? "?…" : "");
	} catch {
		return "[invalid url]";
	}
}

/** The .lex URL of an EXTENSION input. */
export function lexUrl(input, repo = "https://maven.lucee-services.com") {
	const v = String(input ?? "").trim();
	if (!v) throw new Error("EXTENSION is required (groupId:artifactId:version or https URL of a .lex)");
	if (/^https:\/\//i.test(v)) return v;
	if (/^[a-z]+:\/\//i.test(v)) throw new Error(`only https URLs are allowed, got [${redact(v)}]`);
	const parts = v.split(":");
	if (parts.length !== 3 || !parts.every((p) => SAFE.test(p))) {
		throw new Error(`[${v}] is neither groupId:artifactId:version nor an https URL`);
	}
	const [g, a, ver] = parts;
	return `${repo.replace(/\/+$/, "")}/${g.replaceAll(".", "/")}/${a}/${ver}/${a}-${ver}.lex`;
}

// ---------------------------------------------------------------- zip

/** Map of entry name -> () => Buffer, from the central directory (stored and deflated entries). */
export function readZip(buf) {
	let eocd = -1;
	for (let i = buf.length - 22; i >= Math.max(0, buf.length - 22 - 65535); i--) {
		if (buf.readUInt32LE(i) === 0x06054b50) {
			eocd = i;
			break;
		}
	}
	if (eocd < 0) throw new Error("not a zip file (no end of central directory)");
	const count = buf.readUInt16LE(eocd + 10);
	let p = buf.readUInt32LE(eocd + 16);
	const entries = new Map();
	for (let n = 0; n < count; n++) {
		if (buf.readUInt32LE(p) !== 0x02014b50) throw new Error("broken zip central directory");
		const method = buf.readUInt16LE(p + 10);
		const csize = buf.readUInt32LE(p + 20);
		const nameLen = buf.readUInt16LE(p + 28);
		const extraLen = buf.readUInt16LE(p + 30);
		const commentLen = buf.readUInt16LE(p + 32);
		const local = buf.readUInt32LE(p + 42);
		const name = buf.toString("utf8", p + 46, p + 46 + nameLen);
		p += 46 + nameLen + extraLen + commentLen;
		if (name.endsWith("/")) continue;
		entries.set(name, () => {
			if (buf.readUInt32LE(local) !== 0x04034b50) throw new Error(`broken zip entry ${name}`);
			const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
			const data = buf.subarray(start, start + csize);
			if (method === 0) return Buffer.from(data);
			if (method === 8) return inflateRawSync(data);
			throw new Error(`zip entry ${name} uses unsupported compression ${method}`);
		});
	}
	return entries;
}

// ---------------------------------------------------------------- manifests

/** Main section of a MANIFEST.MF as { header: value } (continuation lines joined). */
export function parseManifest(text) {
	const out = {};
	const lines = String(text).replace(/\r\n?/g, "\n").replace(/\n /g, "").split("\n");
	for (const line of lines) {
		if (!line.trim()) break; // end of the main section
		const i = line.indexOf(":");
		if (i > 0) out[line.slice(0, i).trim()] = line.slice(i + 1).trim();
	}
	return out;
}

/** Bundle-SymbolicName (without directives) and Bundle-Version of a jar, null when it is not a bundle. */
export function bundleOfJar(jarBuf) {
	const read = readZip(jarBuf).get("META-INF/MANIFEST.MF");
	if (!read) return null;
	const mf = parseManifest(read().toString("utf8"));
	const name = (mf["Bundle-SymbolicName"] ?? "").split(";")[0].trim();
	if (!name) return null;
	return { name, version: (mf["Bundle-Version"] ?? "0.0.0").trim() };
}

const NAME_KEYS = ["bundleName", "bundle-name", "bundlename"];
const VERSION_KEYS = ["bundleVersion", "bundle-version", "bundleversion"];

function unquote(v) {
	return String(v ?? "").trim().replace(/^"(.*)"$/s, "$1");
}

/**
 * Bundles an extension manifest requires: every {...} entry of a manifest value (jdbc, cache, orm,
 * webservice, search, resource, monitor, amf, event-gateway, ...) with a bundle name and a version.
 * "name" counts as the bundle name only in an entry that also has a "class" (webservice, orm, ...).
 */
export function requiredBundles(manifest) {
	const found = [];
	for (const [header, raw] of Object.entries(manifest)) {
		const value = unquote(raw);
		for (const m of value.matchAll(/\{([^{}]*)\}/g)) {
			const fields = {};
			for (const f of m[1].matchAll(/['"]?([A-Za-z-]+)['"]?\s*:\s*(?:'([^']*)'|"([^"]*)"|([^,'"]+))/g)) {
				fields[f[1]] = (f[2] ?? f[3] ?? f[4] ?? "").trim();
			}
			const lower = Object.fromEntries(Object.entries(fields).map(([k, v]) => [k.toLowerCase(), v]));
			let name = NAME_KEYS.map((k) => lower[k.toLowerCase()]).find(Boolean);
			let version = VERSION_KEYS.map((k) => lower[k.toLowerCase()]).find(Boolean);
			if (!name && lower.class && lower.name) {
				name = lower.name;
				version = version || lower.version;
			}
			if (name) found.push({ name, version: version || "", from: header });
		}
	}
	return found;
}

/** Everything the extension needs or ships, one entry per name@version. */
export function collectBundles(lexBuf) {
	const zip = readZip(lexBuf);
	const mfRead = zip.get("META-INF/MANIFEST.MF");
	if (!mfRead) throw new Error("the .lex has no META-INF/MANIFEST.MF");
	const manifest = parseManifest(mfRead().toString("utf8"));
	const bundles = new Map();
	const notBundles = [];
	for (const [entry, read] of zip) {
		if (!/^jars\/[^/]+\.jar$/i.test(entry)) continue;
		const jar = read();
		let b = null;
		try {
			b = bundleOfJar(jar);
		} catch {
			b = null;
		}
		if (!b) {
			notBundles.push(entry);
			continue;
		}
		const key = `${b.name}@${b.version}`;
		bundles.set(key, { ...b, shipped: true, required: false, entry, jar });
	}
	for (const r of requiredBundles(manifest)) {
		const key = `${r.name}@${r.version}`;
		if (bundles.has(key)) bundles.get(key).required = true;
		else bundles.set(key, { name: r.name, version: r.version, shipped: false, required: true, entry: "", jar: null });
	}
	return {
		extension: { id: unquote(manifest.id), name: unquote(manifest.name), version: unquote(manifest.version) },
		bundles: [...bundles.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)),
		notBundles
	};
}

// ---------------------------------------------------------------- target layout

/** Maven-layout key of a bundle as org.lucee:<Bundle-SymbolicName>:<Bundle-Version>. */
export function bundleBase(name, version) {
	if (!SAFE.test(name) || !SAFE.test(version)) return null;
	return `org/lucee/${name}/${version}/${name}-${version}`;
}

export function minimalPom(name, version) {
	return `<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>
  <groupId>org.lucee</groupId>
  <artifactId>${name}</artifactId>
  <version>${version}</version>
  <packaging>jar</packaging>
  <description>OSGi bundle ${name} ${version}, published from a Lucee extension (.lex) so the update provider can resolve it</description>
</project>
`;
}

const digest = (alg, body) => createHash(alg).update(body).digest("hex");

/** The objects of one bundle, jar first: jar, pom and a .sha1 / .md5 of each. */
export function planObjects(name, version, jar, prefix = "") {
	const base = bundleBase(name, version);
	if (!base) throw new Error(`[${name}] / [${version}] cannot be used in a Maven path`);
	const pom = Buffer.from(minimalPom(name, version));
	const objects = [];
	for (const [ext, body, type] of [
		["jar", jar, "application/java-archive"],
		["pom", pom, "application/xml"]
	]) {
		objects.push({ key: `${prefix}${base}.${ext}`, body, type });
		objects.push({ key: `${prefix}${base}.${ext}.sha1`, body: Buffer.from(digest("sha1", body)), type: "text/plain" });
		objects.push({ key: `${prefix}${base}.${ext}.md5`, body: Buffer.from(digest("md5", body)), type: "text/plain" });
	}
	return objects;
}

// ---------------------------------------------------------------- http

async function httpFetch(url, opts = {}, { timeoutMs = 60000, tries = 3 } = {}) {
	let last;
	for (let i = 0; i < tries; i++) {
		try {
			const res = await fetch(url, { ...opts, headers: { "user-agent": USER_AGENT, ...(opts.headers ?? {}) }, signal: AbortSignal.timeout(timeoutMs) });
			if (res.status >= 500 && i < tries - 1) {
				last = new Error(`HTTP ${res.status}`);
			} else return res;
		} catch (e) {
			last = e;
		}
		await new Promise((r) => setTimeout(r, 1000 * (i + 1)));
	}
	throw new Error(`${opts.method ?? "GET"} ${redact(url)} failed: ${last?.message ?? last}`);
}

async function download(url) {
	const res = await httpFetch(url, { redirect: "follow" }, { timeoutMs: 300000 });
	if (!res.url.startsWith("https://")) throw new Error(`[${redact(url)}] was redirected to a non https URL`);
	if (!res.ok) throw new Error(`download of ${redact(url)} failed, HTTP ${res.status}`);
	const len = Number(res.headers.get("content-length") ?? 0);
	if (len > MAX_LEX_BYTES) throw new Error(`${redact(url)} is larger than ${MAX_LEX_BYTES} bytes`);
	const buf = Buffer.from(await res.arrayBuffer());
	if (buf.length > MAX_LEX_BYTES) throw new Error(`${redact(url)} is larger than ${MAX_LEX_BYTES} bytes`);
	return buf;
}

/** How the update provider answers a bundle: { state: present|missing|error, detail }. */
export function providerState(status, location) {
	if ([301, 302, 303, 307, 308].includes(status) && location) return { state: "present", detail: redact(location) };
	if (status === 200) return { state: "present", detail: "served by the provider" };
	if (status === 404) return { state: "missing", detail: "provider 404" };
	return { state: "error", detail: `provider HTTP ${status}` };
}

async function askProvider(providerUrl, name, version) {
	const url = `${providerUrl.replace(/\/*$/, "/")}${encodeURIComponent(name)}/${encodeURIComponent(version)}`;
	const res = await httpFetch(url, { method: "HEAD", redirect: "manual" });
	return providerState(res.status, res.headers.get("location"));
}

async function repoHas(repo, path) {
	const res = await httpFetch(`${repo.replace(/\/+$/, "")}/${path}`, { method: "HEAD", redirect: "manual" });
	if (res.status === 200 || (res.status >= 300 && res.status < 400)) return true;
	if (res.status === 404) return false;
	throw new Error(`HEAD ${repo}/${path} HTTP ${res.status}`);
}

// ---------------------------------------------------------------- R2 (S3 API, SigV4, no SDK)

export function r2Config(env) {
	const g = (k) => (env[k] ?? "").trim();
	const missing = ["R2_ENDPOINT", "R2_BUCKET", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY"].filter((k) => !g(k));
	if (missing.length) throw new Error(`missing ${missing.join(", ")} (needed when DRY_RUN=false)`);
	let prefix = g("R2_PREFIX").replace(/^\/+/, "");
	if (prefix && !prefix.endsWith("/")) prefix += "/";
	return { endpoint: g("R2_ENDPOINT").replace(/\/+$/, ""), bucket: g("R2_BUCKET"), accessKeyId: g("R2_ACCESS_KEY_ID"), secretAccessKey: g("R2_SECRET_ACCESS_KEY"), prefix };
}

const uriEncode = (v) => encodeURIComponent(v).replace(/[!'()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);

export function signedRequest(cfg, method, key, { body, headers = {} } = {}, date = new Date()) {
	const path = `/${cfg.bucket}/${key.split("/").map(uriEncode).join("/")}`;
	const host = new URL(cfg.endpoint).host;
	const amz = date.toISOString().replace(/[:-]|\.\d{3}/g, "");
	const day = amz.slice(0, 8);
	const bodyHash = digest("sha256", body ?? "");
	const h = { host, "x-amz-date": amz, "x-amz-content-sha256": bodyHash };
	for (const [k, v] of Object.entries(headers)) h[k.toLowerCase()] = String(v);
	const names = Object.keys(h).sort();
	const canonical = [method, path, "", names.map((n) => `${n}:${h[n].trim()}\n`).join(""), names.join(";"), bodyHash].join("\n");
	const scope = `${day}/auto/s3/aws4_request`;
	const toSign = ["AWS4-HMAC-SHA256", amz, scope, digest("sha256", canonical)].join("\n");
	let k = createHmac("sha256", `AWS4${cfg.secretAccessKey}`).update(day).digest();
	for (const part of ["auto", "s3", "aws4_request"]) k = createHmac("sha256", k).update(part).digest();
	const signature = createHmac("sha256", k).update(toSign).digest("hex");
	h.authorization = `AWS4-HMAC-SHA256 Credential=${cfg.accessKeyId}/${scope}, SignedHeaders=${names.join(";")}, Signature=${signature}`;
	delete h.host;
	return { url: cfg.endpoint + path, init: { method, headers: h, body } };
}

async function r2Head(cfg, key) {
	const { url, init } = signedRequest(cfg, "HEAD", key);
	const res = await httpFetch(url, init);
	if (res.status === 404) return false;
	if (res.ok) return true;
	throw new Error(`R2 HEAD ${key} HTTP ${res.status}`);
}

/** true = written, false = already there (412). */
async function r2PutIfAbsent(cfg, obj) {
	const { url, init } = signedRequest(cfg, "PUT", obj.key, {
		body: obj.body,
		headers: { "content-type": obj.type, "content-length": obj.body.length, "if-none-match": "*" }
	});
	const res = await httpFetch(url, init, { timeoutMs: 300000 });
	if (res.status === 412) return false;
	if (!res.ok) throw new Error(`R2 PUT ${obj.key} HTTP ${res.status}: ${(await res.text()).slice(0, 300)}`);
	return true;
}

// ---------------------------------------------------------------- run

export function summaryTable(rows) {
	const head = ["bundle", "version", "from", "status", "detail"];
	const lines = [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`];
	for (const r of rows) lines.push(`| ${r.name} | ${r.version || "(any)"} | ${r.from} | ${r.status} | ${r.detail.replaceAll("|", "\\|")} |`);
	return lines.join("\n");
}

export async function run(env = process.env, log = console.log) {
	const dryRun = (env.DRY_RUN ?? "true").trim().toLowerCase() !== "false";
	const repo = (env.MAVEN_REPO || "https://maven.lucee-services.com").trim();
	const provider = (env.PROVIDER_URL || "https://update.lucee.org/rest/update/provider/download/").trim();
	const url = lexUrl(env.EXTENSION, repo);
	const r2 = dryRun ? null : r2Config(env);
	const prefix = r2?.prefix ?? (env.R2_PREFIX ?? "").trim();

	log(`extension: ${redact(url)}${dryRun ? " (dry run, nothing is written)" : ""}`);
	const lex = await download(url);
	const { extension, bundles, notBundles } = collectBundles(lex);
	log(`${extension.name || "?"} ${extension.version} (id ${extension.id || "?"}): ${bundles.length} bundles, ${notBundles.length} jars without Bundle-SymbolicName`);
	for (const nb of notBundles) log(`  not an OSGi bundle, skipped: ${nb}`);

	const rows = [];
	let failed = 0;
	for (const b of bundles) {
		const from = [b.shipped ? "jars/" : "", b.required ? "manifest" : ""].filter(Boolean).join(" + ");
		const row = { name: b.name, version: b.version, from, status: "", detail: "" };
		rows.push(row);
		try {
			if (!b.version) {
				row.status = "unresolvable";
				row.detail = "required without a version";
				continue;
			}
			const p = await askProvider(provider, b.name, b.version);
			if (p.state === "present") {
				row.status = "present";
				row.detail = p.detail;
				continue;
			}
			if (p.state === "error") {
				row.status = "check-failed";
				row.detail = p.detail;
				failed++;
				continue;
			}
			if (!b.shipped) {
				row.status = "unresolvable";
				row.detail = "provider 404 and the jar is not in the .lex";
				continue;
			}
			const base = bundleBase(b.name, b.version);
			if (!base) {
				row.status = "unresolvable";
				row.detail = "name or version not usable in a Maven path";
				continue;
			}
			// the provider remembers a 404 for 10 minutes, the repository may already have it
			if (await repoHas(repo, `${base}.jar`)) {
				row.status = "present";
				row.detail = `in ${repo}/${base}.jar (provider still answers 404, it caches misses for 10 minutes)`;
				continue;
			}
			const objects = planObjects(b.name, b.version, b.jar, prefix);
			if (dryRun) {
				row.status = "would-upload";
				row.detail = `${objects[0].key} (+ pom, .sha1, .md5), ${b.jar.length} bytes, sha1 ${digest("sha1", b.jar)}`;
				continue;
			}
			if (await r2Head(r2, objects[0].key)) {
				row.status = "present";
				row.detail = `already in R2 at ${objects[0].key}`;
				continue;
			}
			let written = 0;
			for (const o of objects) if (await r2PutIfAbsent(r2, o)) written++;
			const visible = await repoHas(repo, `${base}.jar`).catch(() => false);
			row.status = "uploaded";
			row.detail = `${objects[0].key}, ${written}/${objects.length} objects written${visible ? ", served by " + repo : ", not visible on " + repo + " yet"}`;
		} catch (e) {
			row.status = "failed";
			row.detail = String(e?.message ?? e);
			failed++;
		}
	}

	const table = summaryTable(rows);
	log("");
	log(table);
	if (env.GITHUB_STEP_SUMMARY) {
		appendFileSync(env.GITHUB_STEP_SUMMARY, `### OSGi bundles of ${extension.name || "extension"} ${extension.version}${dryRun ? " (dry run)" : ""}\n\nSource: ${redact(url)}\n\n${table}\n`);
	}
	return { rows, failed, dryRun };
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) {
	run()
		.then((r) => process.exit(r.failed ? 1 : 0))
		.catch((e) => {
			console.error(String(e?.message ?? e));
			process.exit(1);
		});
}
